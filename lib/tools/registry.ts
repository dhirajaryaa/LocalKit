export const TOOL_BY_SLUG = new Map(TOOLS.map((tool) => [tool.slug, tool]));

export function getTool(slug: string): Tool | undefined {
  return TOOL_BY_SLUG.get(slug);
}

export function getToolsByCategory(category: CategoryId): Tool[] {
  return TOOLS.filter((tool) => tool.category === category);
}

export function getCategoryCounts(): Record<CategoryId, number> {
  const counts: Record<CategoryId, number> = {
    images: 0,
    pdf: 0,
    video: 0,
    gif: 0,
    audio: 0,
  };
  for (const tool of TOOLS) counts[tool.category] += 1;
  return counts;
}

export function getRelatedTools(tool: Tool): Tool[] {
  return tool.related
    .map((slug) => getTool(slug))
    .filter((candidate): candidate is Tool => Boolean(candidate))
    .slice(0, 3);
}

